case_enrich_preserve() {
    if [ ! -f "$LIB/merge-enrichment.sh" ]; then no "enrich-preserve: lib/merge-enrichment.sh exists"; return; fi
    ok "enrich-preserve: lib/merge-enrichment.sh exists"
    if [ ! -f "$LIB/gen-projections.sh" ]; then no "enrich-preserve: lib/gen-projections.sh exists"; return; fi
    ok "enrich-preserve: lib/gen-projections.sh exists"

    local REPO="$T/preserve"
    make_repo "$REPO"
    run_in "$LIB/extract-features.sh" wiki_extract "$REPO" >/dev/null 2>&1 || { no "enrich-preserve: extract failed"; return; }
    local STORE="$REPO/.wiki/store.json"
    run_in "$LIB/import-existing.sh" wiki_import_existing "$REPO" >/dev/null 2>&1 || true
    local FS="$REPO/readme/feature-status.md"

    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$REPO" >/dev/null 2>&1 \
        && ok "enrich-preserve: first generation" \
        || { no "enrich-preserve: first generation failed"; return; }
    grep -q "wiki:enrich id=parsing fp=" "$FS" \
        && ok "enrich-preserve: block carries id and fp attributes" \
        || { no "enrich-preserve: no id/fp block in feature-status.md"; return; }
    grep -q "Tokenizes raw" "$FS" \
        && ok "enrich-preserve: imported text embedded on first gen" \
        || no "enrich-preserve: imported text absent on first gen"

    # simulate Claude editing the enrich block in the generated md
    edit_parsing_block "$FS"
    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$REPO" >/dev/null 2>&1 || { no "enrich-preserve: second gen failed"; return; }
    grep -q "EDITED-MARKER-42" "$FS" \
        && ok "enrich-preserve: edited block survives same-fp regen" \
        || no "enrich-preserve: edited block dropped by same-fp regen"

    # stale the feature: its file list changes, so the feature fp moves
    python3 - "$STORE" <<'PY'
import json, sys
path = sys.argv[1]
with open(path, encoding="utf-8") as fh:
    store = json.load(fh)
for f in store["features"]:
    if f["fid"] == "parsing":
        f["files"] = sorted(set(f["files"]) | {"parsing/extra.py"})
with open(path, "w", encoding="utf-8") as fh:
    json.dump(store, fh, indent=2)
    fh.write("\n")
PY
    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$REPO" >/dev/null 2>&1 || { no "enrich-preserve: stale gen failed"; return; }
    if grep -q "EDITED-MARKER-42" "$FS"; then
        no "enrich-preserve: stale block not replaced (edit survived fp change)"
    else
        ok "enrich-preserve: stale block replaced after feature fp change"
    fi
    grep -q "Tokenizes raw" "$FS" \
        && ok "enrich-preserve: stale regen re-attaches text from blocks/" \
        || no "enrich-preserve: stale regen lost the blocks/ enrichment text"
}

