case_pages_shape() {
    if [ ! -f "$LIB/gen-pages.sh" ]; then no "pages-shape: lib/gen-pages.sh exists"; return; fi
    ok "pages-shape: lib/gen-pages.sh exists"
    if [ ! -f "$LIB/lint-pages.sh" ]; then no "pages-shape: lib/lint-pages.sh exists"; return; fi
    ok "pages-shape: lib/lint-pages.sh exists"

    local REPO="$T/pages"
    make_repo "$REPO"
    run_in "$LIB/extract-features.sh" wiki_extract "$REPO" >/dev/null 2>&1 || { no "pages-shape: extract failed"; return; }
    local STORE="$REPO/.wiki/store.json"
    run_in "$LIB/import-existing.sh" wiki_import_existing "$REPO" >/dev/null 2>&1 || true
    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$REPO" >/dev/null 2>&1 || true
    run_in "$LIB/gen-pages.sh" wiki_gen_pages "$STORE" "$REPO" >/dev/null 2>&1 \
        && ok "pages-shape: wiki_gen_pages exit 0" \
        || { no "pages-shape: gen pages failed"; return; }

    local fid page bad=0
    while IFS= read -r fid; do
        [ -n "$fid" ] || continue
        page="$REPO/readme/wiki/$fid/wiki.md"
        if [ ! -f "$page" ]; then no "pages-shape: missing page for $fid"; bad=1; continue; fi
        grep -q '\*\*Source:\*\*' "$page" || { no "pages-shape: $fid page lacks Source grounding"; bad=1; }
        grep -q '^\*\*Status:\*\* dev$' "$page" || { no "pages-shape: $fid page lacks status line"; bad=1; }
        grep -q '<!-- /wiki:enrich -->' "$page" || { no "pages-shape: $fid page lacks enrich block"; bad=1; }
    done <<EOF
$(store_fids "$STORE")
EOF
    [ "$bad" -eq 0 ] && ok "pages-shape: every fid has a page with Source, status, enrich block"

    # features_dir override via .wiki/config.json
    printf '{"features_dir": "docs/wik"}\n' >"$REPO/.wiki/config.json"
    run_in "$LIB/gen-pages.sh" wiki_gen_pages "$STORE" "$REPO" >/dev/null 2>&1 || { no "pages-shape: config regen failed"; return; }
    [ -f "$REPO/docs/wik/parsing/wiki.md" ] \
        && ok "pages-shape: features_dir config override honored (docs/wik/)" \
        || no "pages-shape: config override ignored (no docs/wik/parsing/wiki.md)"

    if run_in "$LIB/lint-pages.sh" wiki_lint "$REPO" >"$T/lint-repo.log" 2>&1; then
        ok "pages-shape: wiki_lint passes on generated pages"
    else
        no "pages-shape: wiki_lint failed on generated pages: $(tail -3 "$T/lint-repo.log")"
    fi
}

