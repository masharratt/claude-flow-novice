#!/usr/bin/env bash
# tests/test-wiki-generate.sh - cfn-wiki Phase 3 harness.
# Covers: lib/import-existing.sh (enrich-import: hand-written fixture rows
# reappear as enrich blocks, unmatched rows orphaned, run is idempotent and a
# GENERATED marker makes it a no-op), lib/merge-enrichment.sh +
# lib/gen-projections.sh (enrich-preserve: edited block survives a same-fp
# regen, stale block replaced and re-attached from blocks/; projections-lint:
# generated fixture projections pass the real cfn-doc-lint), lib/gen-pages.sh
# (pages-shape: every fid gets a page with Source grounding, features_dir
# config honored), lib/lint-pages.sh (lint-catches: seeded bad page fails,
# good page passes, zero-page dir says so). Plan: fuzzy-whistling-eich Phase 3.
# Isolation: every case runs in temp dirs; the shipped fixture is only written
# by projections-lint (extract + generate into it, gitignored store aside),
# which is the plan's verify command. Hand-written fixture docs are restored
# from heredocs below so case order never matters.
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
LIB="$ROOT/.claude/skills/cfn-wiki/lib"
FIXTURE="$ROOT/tests/fixtures/wiki-fixture-repo"
DOCLINT="$ROOT/.claude/skills/cfn-doc-lint/execute.sh"

T="$(mktemp -d "${TMPDIR:-/tmp}/wiki-generate-test-XXXXXX")"
cleanup() { rm -rf "$T"; }
trap cleanup EXIT

PASS=0; FAIL=0; SKIP=0
ok()   { echo "PASS: $1"; PASS=$((PASS+1)); }
no()   { echo "FAIL: $1"; FAIL=$((FAIL+1)); }
skip() { echo "SKIP: $1"; SKIP=$((SKIP+1)); }

for dep in bash python3 git mktemp; do
    command -v "$dep" >/dev/null 2>&1 || { echo "FATAL: $dep not on PATH"; exit 1; }
done
[ -f "$DOCLINT" ] || { echo "FATAL: cfn-doc-lint execute.sh missing at $DOCLINT"; exit 1; }

# Run a lib function in a clean subshell: run_in <lib.sh> <fn> [args...]
run_in() {
    bash -c '
        set -uo pipefail
        source "$1"
        shift
        "$@"
    ' _ "$@"
}

# Evaluate a python expression over a store.json: store_val <file> <expr>
store_val() {
    python3 -c '
import json, sys
with open(sys.argv[1], encoding="utf-8") as fh:
    s = json.load(fh)
print(eval(sys.argv[2]))
' "$1" "$2"
}

store_fids() { # <store> -> newline-separated fids
    python3 -c '
import json, sys
with open(sys.argv[1], encoding="utf-8") as fh:
    s = json.load(fh)
print("\n".join(f["fid"] for f in s.get("features", [])))
' "$1"
}

# The pristine hand-written docs (pre-wiki state of the fixture readme).
write_handwritten_readme() { # <dest-repo>
    mkdir -p "$1/readme"
    cat >"$1/readme/feature-status.md" <<'EOF'
# Fixture Repo — Feature Status

**Last Updated:** 2026-09-12 (fixture placeholder; regenerated by `wiki sync`)

Status Legend: `prod | beta | dev | stub | deprecated`

| Feature | Status | Description | Dependencies | Known Limitations |
|---------|--------|-------------|--------------|-------------------|
| parsing | dev | Tokenizes raw `name,value` lines into structured records (fixture sample). | util | Placeholder row; replaced by `wiki sync` generation. |
| reporting | dev | Renders parsed records as text tables and TS count summaries (fixture sample). | parsing | Placeholder row; replaced by `wiki sync` generation. |
EOF
    cat >"$1/readme/state-machines.md" <<'EOF'
# Fixture Repo — State Machines

**Source:** placeholder — regenerated by `wiki sync` from `.wiki/store.json`

## Report

**Source:** service.py `build_report` (fixture placeholder)

### States

| State | Meaning |
|-------|---------|
| empty | No parsed records yet |
| built | Report rendered from parsed records |

### Transitions

| From | To | Trigger | Guard |
|------|----|---------|-------|
| empty | built | `build_report` called with >=1 line | none |
EOF
}

# Fixture copy with no .wiki and the pristine hand-written readme.
make_repo() { # <dest>
    local dest="$1"
    mkdir -p "$dest"
    cp -r "$FIXTURE/." "$dest/"
    rm -rf "$dest/.wiki" "$dest/readme"
    write_handwritten_readme "$dest"
}

blocks_dir() { printf '%s/.wiki/enrich/blocks' "$1"; }
blocks_sum() { cat "$1"/.wiki/enrich/blocks/*.md 2>/dev/null | sha256sum | cut -d" " -f1; }

# Insert a marker line inside the id=parsing enrich block of a generated file.
edit_parsing_block() { # <feature-status.md>
    python3 - "$1" <<'PY'
import sys
path = sys.argv[1]
with open(path, encoding="utf-8") as fh:
    text = fh.read()
start = text.index("<!-- wiki:enrich id=parsing fp=")
end = text.index("<!-- /wiki:enrich -->", start)
text = text[:end] + "EDITED-MARKER-42\n" + text[end:]
with open(path, "w", encoding="utf-8") as fh:
    fh.write(text)
PY
}

