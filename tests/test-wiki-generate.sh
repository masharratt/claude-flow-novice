case_projections_lint() {
    if [ ! -f "$LIB/gen-projections.sh" ]; then no "projections-lint: lib/gen-projections.sh exists"; return; fi
    ok "projections-lint: lib/gen-projections.sh exists"

    # the plan's verify command: generate the shipped fixture projections in
    # place, then run the real linter over the fixture repo. Extraction runs
    # on a plain temp copy and its store is installed into the fixture: the
    # fixture is a non-repo dir inside THIS repo, so a direct extract would
    # walk the whole 1455-commit outer history in extract's O(k^2) coupling
    # step (the cap its own cfn: comment anticipates). A no-git copy yields
    # the same degraded store for these file contents.
    local TMPSRC="$T/proj-src"
    mkdir -p "$TMPSRC"
    cp -r "$FIXTURE/." "$TMPSRC/"
    rm -rf "$TMPSRC/.wiki"
    run_in "$LIB/extract-features.sh" wiki_extract "$TMPSRC" >/dev/null 2>&1 \
        && ok "projections-lint: extract on fixture content copy" \
        || { no "projections-lint: extract on fixture copy failed"; return; }
    mkdir -p "$FIXTURE/.wiki"
    cp "$TMPSRC/.wiki/store.json" "$FIXTURE/.wiki/store.json" \
        && ok "projections-lint: store installed into fixture" \
        || { no "projections-lint: store install failed"; return; }
    local STORE="$FIXTURE/.wiki/store.json"
    run_in "$LIB/import-existing.sh" wiki_import_existing "$FIXTURE" >/dev/null 2>&1 || true
    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$FIXTURE" >/dev/null 2>&1 \
        && ok "projections-lint: generate fixture projections" \
        || { no "projections-lint: generate failed"; return; }

    local FS="$FIXTURE/readme/feature-status.md" SM="$FIXTURE/readme/state-machines.md"
    local head_fs head_sm
    head_fs="$(head -2 "$FS")"; head_sm="$(head -2 "$SM")"
    printf '%s\n%s\n' "$head_fs" "$head_sm" | grep -q "GENERATED by cfn-wiki sync. DO NOT EDIT." \
        && ok "projections-lint: GENERATED header is line 1 of both projections" \
        || no "projections-lint: GENERATED header misplaced"
    printf '%s\n%s\n' "$head_fs" "$head_sm" | grep -Eq "wiki-fp: [0-9a-f]{64}" \
        && ok "projections-lint: wiki-fp line 2 of both projections" \
        || no "projections-lint: wiki-fp line missing or malformed"

    grep -q '^| Feature | Status | Description | Dependencies | Known Limitations |$' "$FS" \
        && ok "projections-lint: exact required columns in feature-status.md" \
        || no "projections-lint: feature-status.md column row wrong"
    for tok in prod beta dev stub deprecated; do
        grep -qw "$tok" "$FS" || no "projections-lint: status token $tok absent from feature-status.md"
    done
    ok "projections-lint: all five status tokens present (legend)"

    grep -q '```mermaid' "$SM" \
        && ok "projections-lint: mermaid fences kept in state-machines.md" \
        || no "projections-lint: state-machines.md lost mermaid fences"
    local n_entities n_src
    n_entities="$(grep -c '^## ' "$SM" || true)"
    n_src="$(grep -c '\*\*Source:\*\*' "$SM" || true)"
    [ "$n_entities" -ge 2 ] && [ "$n_src" -ge "$n_entities" ] \
        && ok "projections-lint: every entity carries Source grounding ($n_entities entities)" \
        || no "projections-lint: entity/Source counts wrong (entities=$n_entities src=$n_src)"
    local fids entities_ok=1 fid
    while IFS= read -r fid; do
        [ -n "$fid" ] || continue
        grep -Eq "^## [0-9]+\. $fid$" "$SM" || entities_ok=0
    done <<EOF
$(store_fids "$STORE")
EOF
    [ "$entities_ok" -eq 1 ] \
        && ok "projections-lint: one numbered H2 entity per store fid" \
        || no "projections-lint: a store fid has no state-machines entity"

    if bash "$DOCLINT" "$FIXTURE" >"$T/doclint.log" 2>&1; then
        ok "projections-lint: cfn-doc-lint exit 0 on generated fixture projections"
    else
        no "projections-lint: cfn-doc-lint failed: $(tail -5 "$T/doclint.log")"
    fi
}

