case_lint_catches() {
    local D="$T/lint"
    mkdir -p "$D/good" "$D/bad" "$D/empty"
    cat >"$D/good/wiki.md" <<'EOF'
# good

**Source:**

- `src/a.py`

**Status:** dev

<!-- wiki:enrich id=good fp=abc -->
note
<!-- /wiki:enrich -->
EOF
    cat >"$D/bad/wiki.md" <<'EOF'
# bad

**Status:** shipped

No grounding, no enrich block here.
EOF

    if run_in "$LIB/lint-pages.sh" wiki_lint "$D/good" >"$T/lint-good.log" 2>&1; then
        ok "lint-catches: good page passes"
    else
        no "lint-catches: good page rejected: $(tail -3 "$T/lint-good.log")"
    fi

    local rc=0
    run_in "$LIB/lint-pages.sh" wiki_lint "$D" >"$T/lint-bad.log" 2>&1 || rc=$?
    if [ "$rc" -eq 1 ]; then
        ok "lint-catches: seeded bad page fails with exit 1"
    else
        no "lint-catches: bad page exit=$rc (want 1)"
    fi
    grep -q "bad/wiki.md" "$T/lint-bad.log" \
        && ok "lint-catches: finding names the offending file" \
        || no "lint-catches: finding does not name bad/wiki.md"
    grep -q "Source" "$T/lint-bad.log" \
        && ok "lint-catches: missing Source grounding reported" \
        || no "lint-catches: Source check silent"
    grep -q "shipped" "$T/lint-bad.log" \
        && ok "lint-catches: bad status token reported" \
        || no "lint-catches: status token check silent"

    if run_in "$LIB/lint-pages.sh" wiki_lint "$D/empty" >"$T/lint-empty.log" 2>&1; then
        grep -q "0 wiki.md" "$T/lint-empty.log" \
            && ok "lint-catches: zero-page dir exits 0 and says it examined nothing" \
            || no "lint-catches: zero-page dir passed silently without a count"
    else
        no "lint-catches: zero-page dir should not fail"
    fi
}

