case_enrich_import() {
    if [ ! -f "$LIB/import-existing.sh" ]; then no "enrich-import: lib/import-existing.sh exists"; return; fi
    ok "enrich-import: lib/import-existing.sh exists"

    local REPO="$T/import"
    make_repo "$REPO"
    run_in "$LIB/extract-features.sh" wiki_extract "$REPO" >/dev/null 2>&1 \
        && ok "enrich-import: extract on temp copy" \
        || { no "enrich-import: extract failed"; return; }
    local STORE="$REPO/.wiki/store.json"
    store_fids "$STORE" | grep -q parsing \
        && ok "enrich-import: store has parsing fid" \
        || no "enrich-import: store lacks parsing fid"
    append_match_rows "$REPO"

    if run_in "$LIB/import-existing.sh" wiki_import_existing "$REPO" >"$T/import.log" 2>&1; then
        ok "enrich-import: wiki_import_existing exit 0"
    else
        no "enrich-import: import failed: $(tail -3 "$T/import.log")"
        return
    fi

    local B; B="$(blocks_dir "$REPO")"
    [ -f "$B/parsing.md" ] && grep -q "Tokenizes raw" "$B/parsing.md" \
        && ok "enrich-import: parsing row carried into blocks/parsing.md" \
        || no "enrich-import: parsing block missing or wrong content"
    [ -f "$B/reporting.md" ] && grep -q "Renders parsed records" "$B/reporting.md" \
        && ok "enrich-import: reporting row carried into blocks/reporting.md" \
        || no "enrich-import: reporting block missing or wrong content"
    grep -q "imported from readme/feature-status.md" "$B/parsing.md" \
        && ok "enrich-import: block records provenance" \
        || no "enrich-import: block lacks provenance marker"

    # match levels: a = exact slug, b = common-prefix strip, c = token overlap
    grep -q "level a" "$T/import.log" \
        && ok "enrich-import: level a (exact slug) logged" \
        || no "enrich-import: level a match not logged"
    grep -q "level b" "$T/import.log" \
        && ok "enrich-import: level b (prefix strip: cfn-loop-task) logged" \
        || no "enrich-import: level b match not logged"
    grep -q "level c" "$T/import.log" \
        && ok "enrich-import: level c (token overlap) logged" \
        || no "enrich-import: level c match not logged"
    [ -f "$B/loop-task.md" ] && grep -q "Coordinates the CFN loop agents" "$B/loop-task.md" \
        && ok "enrich-import: prefixed row matched fid loop-task (level b)" \
        || no "enrich-import: cfn-loop-task row did not reach blocks/loop-task.md"
    grep -q "Runs jobs round-robin" "$B/loop-task.md" \
        && ok "enrich-import: token-overlap row matched the same fid (level c)" \
        || no "enrich-import: Task Runner Loop row did not match loop-task"
    [ -f "$B/entity-loop-task.md" ] && grep -q "job received" "$B/entity-loop-task.md" \
        && ok "enrich-import: entity Loop Task matched by exact slug (level a)" \
        || no "enrich-import: entity Loop Task not carried"

    # Level d (path containment) removed: single generic tokens matched the
    # wrong modules on real data ('GOAP Planner' -> src). Weak matches are
    # worse than orphans; the appendix + enrichment pass handle the rest.
    grep -q "level d" "$T/import.log" \
        && no "enrich-import: level d still firing (removed from ladder)" \
        || ok "enrich-import: level d no longer used"
    if [ -f "$B/orphan-feature-2.md" ] || grep -q "Report rendered" "$B"/orphan-*.md 2>/dev/null; then
        ok "enrich-import: Report row orphaned, not mis-attached"
    else
        no "enrich-import: Report row matched something unexpected"
    fi

    [ -f "$B/orphan-feature-1.md" ] && grep -q "No store counterpart at all" "$B/orphan-feature-1.md" \
        && ok "enrich-import: unmatched row kept as orphan-feature-1 block" \
        || no "enrich-import: unmatched row dropped (no orphan-feature block)"
    grep -q "Waiting for widget jobs" "$B"/orphan-entity-*.md 2>/dev/null \
        && ok "enrich-import: unmatched entity kept as an orphan-entity block" \
        || no "enrich-import: unmatched entity dropped (no orphan-entity block)"
    [ -f "$REPO/.wiki/enrich/orphans.md" ] && grep -q "Totally Unrelated Widget" "$REPO/.wiki/enrich/orphans.md" \
        && ok "enrich-import: orphans.md ledger still written" \
        || no "enrich-import: orphans.md missing"

    # idempotent without a marker: second run rewrites identical bytes
    local sum1 sum2
    sum1="$(blocks_sum "$REPO")"
    run_in "$LIB/import-existing.sh" wiki_import_existing "$REPO" >/dev/null 2>&1 || true
    sum2="$(blocks_sum "$REPO")"
    [ -n "$sum1" ] && [ "$sum1" = "$sum2" ] \
        && ok "enrich-import: rerun without marker rewrites identical blocks" \
        || no "enrich-import: rerun changed blocks ($sum1 vs $sum2)"
    [ "$(grep -c "^## Totally Unrelated Widget" "$REPO/.wiki/enrich/orphans.md")" -eq 1 ] \
        && ok "enrich-import: orphans.md rewritten, not appended" \
        || no "enrich-import: orphans.md duplicated orphan entries"

    # marker no-op: generated projections carry the marker, import skips
    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$REPO" >/dev/null 2>&1 \
        && ok "enrich-import: gen-projections wrote marker" \
        || { no "enrich-import: gen-projections failed"; return; }
    grep -q "GENERATED by cfn-wiki" "$REPO/readme/feature-status.md" \
        && ok "enrich-import: GENERATED marker present" \
        || no "enrich-import: GENERATED marker missing"

    # zero-loss: unmatched rows surface in the generated projections
    local FS="$REPO/readme/feature-status.md" SM="$REPO/readme/state-machines.md"
    grep -q "## Appendix. Imported notes (unmatched)" "$FS" \
        && grep -q "No store counterpart at all" "$FS" \
        && grep -q "wiki:enrich id=orphan-feature-1 " "$FS" \
        && ok "enrich-import: orphan row embedded in feature-status appendix" \
        || no "enrich-import: orphan row missing from feature-status appendix"
    grep -q "## Appendix. Imported notes (unmatched)" "$SM" \
        && grep -q "Waiting for widget jobs" "$SM" \
        && grep -q "wiki:enrich id=orphan-entity-1 " "$SM" \
        && ok "enrich-import: orphan entity embedded in state-machines appendix" \
        || no "enrich-import: orphan entity missing from state-machines appendix"

    local sum3
    sum3="$(blocks_sum "$REPO")"
    run_in "$LIB/import-existing.sh" wiki_import_existing "$REPO" >/dev/null 2>&1 || true
    [ "$sum3" = "$(blocks_sum "$REPO")" ] \
        && ok "enrich-import: rerun with GENERATED marker is a no-op" \
        || no "enrich-import: marker run still rewrote blocks"

    # appendix survives a regeneration with no re-import
    run_in "$LIB/gen-projections.sh" wiki_gen_projections "$STORE" "$REPO" >/dev/null 2>&1 || { no "enrich-import: appendix regen failed"; return; }
    grep -q "No store counterpart at all" "$FS" && grep -q "Waiting for widget jobs" "$SM" \
        && ok "enrich-import: appendix blocks survive regeneration" \
        || no "enrich-import: appendix lost on regen (zero-content-loss violated)"
}

